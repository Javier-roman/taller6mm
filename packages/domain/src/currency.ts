export const CurrencyCodeSchema = z.enum(CURRENCY_CODES, { error: 'Moneda no válida: usa un código ISO 4217 vigente' });

/** Código de moneda ISO 4217 en mayúsculas (EUR, USD, GBP, PLN, HKD…). */
export type CurrencyCode = z.infer<typeof CurrencyCodeSchema>;

const ZERO_DECIMALS = new Set<CurrencyCode>([
  'BIF',
  'CLP',
  'DJF',
  'GNF',
  'ISK',
  'JPY',
  'KMF',
  'KRW',
  'PYG',
  'RWF',
  'UGX',
  'VND',
  'VUV',
  'XAF',
  'XOF',
  'XPF',
]);
const THREE_DECIMALS = new Set<CurrencyCode>(['BHD', 'IQD', 'JOD', 'KWD', 'LYD', 'OMR', 'TND']);

/** Decimales de la unidad menor según ISO 4217 (2 para EUR: 1 € = 100 céntimos). */
export function minorUnitDigits(currency: CurrencyCode): 0 | 2 | 3 {
  if (ZERO_DECIMALS.has(currency)) return 0;
  if (THREE_DECIMALS.has(currency)) return 3;
  return 2;
}
